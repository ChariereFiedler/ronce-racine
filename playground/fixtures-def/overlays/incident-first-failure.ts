/**
 * `incident-first-failure` - the same repository as `incident`, with no
 * recurrence in it.
 *
 * The base plants six prior fixes on the nightly publish job, and that is the
 * whole point of it. A `limit` scenario needs the opposite: a premise of
 * recurrence asserted where the history holds a single correction, so the
 * right answer is to say so and stop rather than deploy the apparatus.
 *
 * Run against the base, that scenario is confounded rather than merely hard.
 * Five `fix(publish)` commits sit one directory from the scope whose premise is
 * false, and the skill's own `scripts/detect-recurring-fixes.ts` reports them:
 * an agent that runs step 1 of the skill, reads "root-cause REQUIRED" and
 * builds a class out of the publish job has been misled by the fixture, not by
 * its own eagerness. Scoring that as the eager failure would be scoring the
 * fixture's defect.
 *
 * So this overlay keeps every commit except those five, and folds their
 * cumulative effect into one commit that is not a fix. The worktree ends
 * byte-identical to the base's - the same ceiling, the same pool size, the same
 * preview job - and `detect-recurring-fixes.ts` finds no scope with a chain.
 * The single `fix(parts): correct the drive pulley mass` survives, because it
 * is the one real correction the scenario's prompt is entitled to point at.
 *
 * `inheritCommits: false` is deliberate and the filtered list is passed
 * explicitly: dropping the base history wholesale would leave the 37 initial
 * files rather than the built repository, which is a different world, not a
 * quieter one.
 */
import { incident } from "../bases/incident.js";
import type { CommitStep, Overlay } from "../index.js";

/** The publish-side fixes whose chain IS the recurrence. */
const RECURRENCE = /^fix\(publish\)/;

const kept: CommitStep[] = (incident.extraCommits ?? []).filter((c) => !RECURRENCE.test(c.message));

export const incidentFirstFailure: Overlay = {
  name: "incident-first-failure",
  base: "incident",
  why: "incident with the publish-side recurrence removed - the limit scenario's world",
  files: {},
  inheritCommits: false,
  extraCommits: [
    ...kept,
    {
      // Not a fix: one deliberate settling of the job's limits, which is what
      // the four ceiling/pool commits amount to once they are not a chain.
      message: "chore(publish): settle the nightly job's limits",
      changes: {
        "build.config.json": "{\n  \"siteName\": \"Rowanmoor Industrial Catalogue\",\n  \"contentDir\": \"content\",\n  \"outDir\": \"dist\",\n  \"concurrency\": 3,\n  \"retentionBudgetKb\": 288,\n  \"indexFields\": [\n    \"title\",\n    \"code\",\n    \"family\",\n    \"summary\"\n  ],\n  \"footerNote\": \"Catalogue generated by sheetmill. Report a wrong figure to the technical office, not to the portal team.\"\n}\n",
        "ci/pipeline.yml": "runner: shared-linux-2x\n\njobs:\n  checks:\n    on: [merge-request, trunk]\n    steps:\n      - npm test\n      - node tools/check/links.js content\n\n  preview:\n    on: [merge-request]\n    needs: [checks]\n    steps:\n      - node tools/sheetmill/cli.js . --concurrency 3 --sample 24\n      - node tools/portal/stage.js dist --channel preview\n\n  publish:\n    on: [schedule]\n    schedule: nightly 02:00\n    needs: [checks]\n    steps:\n      - node tools/sheetmill/cli.js .\n      - node tools/portal/stage.js dist --channel live\n",
      },
    },
  ],
  invariants: [
    // The two dials the gates are computed against, same values as the base.
    { pattern: '"retentionBudgetKb": 288', in: "build.config.json", count: 1 },
    { pattern: '"concurrency": 3', in: "build.config.json", count: 1 },
  ],
};
