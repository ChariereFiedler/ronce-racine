/**
 * `maturity` - the audit world: a target that is genuinely uneven.
 *
 * `briarford-intake` takes street reports - a missed collection, a blocked
 * gully, a light out - from a council call centre and hands them to the works
 * department. One process, no dependencies, 31 tests on `node --test`.
 *
 * A uniform target cannot discriminate between two audits, because both write
 * "some things are good, some are bad". So two domains here are genuinely at
 * the state of the art (observability, release management), two are genuinely
 * poor (testing, data protection), and three decisions are planted where a
 * shallow audit reaches a confident, evidenced, wrong answer:
 *
 * - **A control that controls nothing.** The `quality` job runs `npm run gate`
 *   on every branch. The gate exits non-zero only under `--enforce`, and
 *   `package.json` stopped passing it in `chore(ci): run the quality rules on
 *   every branch` - the same commit that widened the job. Five rule failures
 *   have accumulated since. The README and a prior review both still say the
 *   gate blocks, because both were written while it did.
 * - **A gap that is not a gap.** Nothing here dumps, restores or expires
 *   anything: the cluster moved to another team, and the only place that says
 *   so is item 6 of `ops/onboarding.md`, which never uses the word "backup".
 *   The confirming evidence is a deletion, so it is invisible without `git log`.
 * - **An inverted trap.** The deploy log records outcomes and lead times, so
 *   the delivery metrics that "always need a dashboard" are computable here.
 *   Marking something non-auditable is not free.
 *
 * The house format is `docs/audits/`: a template plus two filled reports about
 * OTHER projects, both with a populated non-auditable section. That is
 * deliberate - it hands the vocabulary to both arms, so a gate over this world
 * can only key on which questions get marked what, never on the words.
 *
 * What each part is for is written next to it below. The answer key - the
 * ranked wrong answers, and the argument for how a careful unaided agent
 * fails - is in EXPECTED.md, which the materialiser keeps out of git.
 */

