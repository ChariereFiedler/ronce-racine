/**
 * `surface` - the frontend world, where the answer is never in the file the
 * question points at.
 *
 * A harbour office runs a server-rendered staff console: berths, vessels,
 * bookings, an arrivals board. There is no framework and no build step, so
 * every screen is a function returning a node tree and every test is a string
 * assertion. That is deliberate: the three defects below are all invisible to
 * a type checker, and two of them are invisible to the suite that ships.
 *
 * Three difficulties live here, and none of them is stated anywhere in the
 * tree:
 *
 * 1. `StatusPill` has NINE call sites. Seven screens import the file directly.
 *    Two import `StateChip` from `src/components/kit.js`, which re-exports it
 *    under the pattern library's name. A grep for the component reaches seven
 *    of the nine, the repository's own reporting tool reaches the same seven
 *    because it greps the same word, and the component's record in
 *    `docs/pattern-library/` was generated from that tool.
 *
 * 2. A raw `tally` block is hand-written on four screens and should be one
 *    component - plus a fifth occurrence in `src/print/`, which must NOT be
 *    migrated, because the billing service renders that sheet without the
 *    console stylesheet. Nothing labels the fifth as special except the
 *    module's own docstring.
 *
 * 3. `NoticeCard` puts its severity modifier on the title element instead of
 *    the card. `.notice--danger .notice__actions .btn` in `console.css` is
 *    therefore never applied: the modifier is a SIBLING of the actions, not
 *    an ancestor. `npm test` passes, including a test that asserts the tone
 *    class is present, because it is - on the wrong node.
 *
 * The decoys are the parts a reader believes. `docs/pattern-library/status-pill.md`
 * states seven call sites and cites the tool that produced it; `docs/backlog.md`
 * says the panels are behind a flag and safe to skip (the flag defaults to
 * true and nothing overrides it); and the same backlog closes the notice
 * complaint as a stale-stylesheet problem, which the pipeline's month-long
 * cache header makes entirely plausible.
 *
 * Directory names avoid `build`, `dist`, `target` and `coverage`: snapshotRepo
 * prunes those, so anything under them is invisible to every gate and to the
 * transposition denylist.
 *
 * The answer key - the wrong answers, and the argument for how a careful
 * unaided agent fails - is EXPECTED.md, which the materialiser keeps out of git.
 */

