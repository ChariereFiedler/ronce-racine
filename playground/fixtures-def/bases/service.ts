/**
 * `service` - the backend world.
 *
 * `millrace` is the back office two dozen independent repair shops run their
 * day on. Every shop is a tenant: its work orders, its bays, its roster, its
 * quotes. Reads and writes go through a repository bound to one shop, and the
 * architecture note says so in as many words.
 *
 * One read does not. The dashboard header strip takes a shop id, uses it to
 * look up that shop's grace period, and then counts rows across the whole
 * table. It has a prior fix on the same three lines that did not notice, a
 * cosmetic refactor sitting on top of it so blame lands nowhere useful, and a
 * repository scoping test written afterwards that covers the repository and
 * not the view. Three other places read the tables raw and are meant to: the
 * operator registry, the shared rate book and the delivery worker.
 *
 * The vocabulary drifted the way it does. The table is `tickets`, the domain
 * says work order, the current wire says job - and `job` is also what the
 * retry loop calls a queued delivery. `estimate` and `quote` read as synonyms
 * and are two different things.
 *
 * The pending change - the free-text `assignee` becoming a reference to the
 * roster - was tried once, in one migration, and came back. The tablets on the
 * shop floor are not on a release cadence anybody here controls, the nightly
 * extract reads the column, and some of the names in it were never technicians.
 * `ops/backlog.md` proposes doing it in one go over a quiet Sunday.
 *
 * `src/domain/work-order.js` imports the clock from infrastructure. That is the
 * one import in the tree pointing the wrong way, and it is why the overdue
 * tests cannot fix the time.
 *
 * Nothing is under a directory called `build`, `dist` or `target`: snapshotRepo
 * prunes those, and a tool living in one is invisible to every gate and to the
 * transposition denylist.
 *
 * The answer key - the wrong answers, and the argument for how a careful
 * unaided agent fails - is in EXPECTED.md, which the materialiser keeps out of
 * git.
 */

