/**
 * `incident` - the world where one defect class keeps being treated as six
 * separate incidents.
 *
 * A datasheet portal renders one page per part per market it is sold in. The
 * nightly publish job trips a self-imposed retention ceiling, and it has been
 * "fixed" six times in twenty-nine days: two raises of the ceiling, two
 * reductions of the render pool, one deletion of the instrument that had
 * started to fail, and one alignment of a second job's pool with the first.
 * Every one of them worked, for a few days.
 *
 * The confirmed cause is a default nobody wrote. `tools/sheetmill/plan.js`
 * renders every market directory it finds on disk, so the amount of work
 * grows whenever sales-ops merges a folder, and no ceiling was ever going to
 * be enough. Two rival hypotheses are partially true and evidenced in `ops/` by
 * colleagues who had the same facts: the shared runner really is under
 * pressure, and the pool size really does move the peak. That is why an
 * investigation stopping at either one produces a wrong answer with a
 * citation.
 *
 * The renderer is `tools/sheetmill/` rather than `tools/build/` on purpose:
 * snapshotRepo prunes any directory named `build`, so a tool living under that
 * name is invisible to every gate and to the transposition denylist.
 *
 * What each part of the world is for is written next to it below. The answer
 * key - the wrong answers, and the argument for how a careful unaided agent
 * fails - is in EXPECTED.md, which the materialiser keeps out of git.
 */

/**
 * A file body from its lines. Fixture content is data, not code: writing it as
 * lines keeps a 30-line datasheet readable here and keeps "\n" out of it.
 */
const doc = (...lines: string[]): string => lines.join("\n") + "\n";

/** The same, with no trailing newline: for a patch spliced into a file. */
const rows = (...lines: string[]): string => lines.join("\n");

/** JSON as this repository stores it: two spaces, one trailing newline. */
const json = (value: unknown): string => JSON.stringify(value, null, 2) + "\n";

/**
 * One datasheet. `summary` is not stored here because the file repeats the
 * lead paragraph into its header - the search index reads the header, and
 * nothing re-derives it when the body changes.
 */
interface PartRecord {
  title: string;
  code: string;
  family: string;
  material: string;
  finish: string;
  tolerance: string;
  massGrams: string;
  packSize: string;
  /** Ids from content/certifications.json, comma separated. */
  certifications: string;
  /** Market codes the part is not sold in, comma separated. */
  withdrawn: string;
  /** The body below the header separator. Line [2] is the lead paragraph. */
  body: string[];
}

interface MarketRecord {
  code: string;
  name: string;
  currency: string;
  warehouse: string;
  leadTimeDays: number;
  certifications: string[];
  legalLine: string;
}

/**
 * A datasheet as the repository stores it. `override` exists for the one part
 * whose figure was wrong at the initial import and corrected later, so the
 * record below can hold the value the repository ends on.
 */
const datasheet = (slug: string, override: Partial<PartRecord> = {}): string => {
  const p = { ...PARTS[slug], ...override };
  return doc(
    "title: " + p.title,
    "code: " + p.code,
    "family: " + p.family,
    "summary: " + p.body[2],
    "material: " + p.material,
    "finish: " + p.finish,
    "tolerance: " + p.tolerance,
    "massGrams: " + p.massGrams,
    "packSize: " + p.packSize,
    "certifications: " + p.certifications,
    "withdrawn: " + p.withdrawn,
    "---",
    ...p.body,
  );
};

